"""Per-user LIVIST job directories in the standard CryoStack workspace::

    <owner_root>/livist/jobs/<job_id>/
        config.toml                  LIVIST configuration written by CryoStack
        data/                        LIVIST's data directory (inputs + products)
        frontend/public/             temperature-sources.json
        logs/generate.log            bounded output of scripts/generate
        manifest.json                artifacts, checksums, provenance, validation
        tmp/

``<owner_root>`` is ``owner_root(user)``, the directory CryoLauncher, ICESEE
and Frozen Legacies use for the same account. Job IDs are generated by the
server and every path is resolved and checked to stay inside the user's
LIVIST root.
"""
from __future__ import annotations

import re
import uuid
from pathlib import Path

from cryostack_src.workspace.identity import WorkspaceIdentityError, WorkspaceUser
from cryostack_src.workspace.manager import WorkspacePermissionError
from cryostack_src.workspace.roots import owner_root

APPLICATION_DIRNAME = "livist"
JOBS_DIRNAME = "jobs"
_JOB_ID = re.compile(r"[0-9a-f]{32}")


def new_job_id() -> str:
    return uuid.uuid4().hex


def is_valid_job_id(value: object) -> bool:
    return isinstance(value, str) and _JOB_ID.fullmatch(value) is not None


def workspace_user_for(user) -> WorkspaceUser:
    user_id = str(getattr(user, "id", "") or "").strip()
    if not user_id:
        raise WorkspaceIdentityError("Authenticated CryoStack identity was not provided.")
    return WorkspaceUser(user_id=user_id, display_name=str(getattr(user, "display_name", "") or ""),
                         source="cryostack-auth")


class LivistWorkspace:
    def __init__(self, user: WorkspaceUser, *, workspace_root: str | Path | None = None):
        if not user.is_authenticated:
            raise WorkspaceIdentityError("Authenticated CryoStack identity was not provided.")
        self.user = user
        self._owner_root = owner_root(user, workspace_root=workspace_root)
        self.root = (self._owner_root / APPLICATION_DIRNAME).resolve()
        self.jobs_root = (self.root / JOBS_DIRNAME).resolve()
        if not self.jobs_root.is_relative_to(self._owner_root):
            raise WorkspacePermissionError("LIVIST workspace escaped its user root.")

    def contain(self, path: str | Path) -> Path:
        resolved = Path(path).resolve()
        if not resolved.is_relative_to(self.root):
            raise WorkspacePermissionError("Path is outside your LIVIST workspace.")
        return resolved

    def job_dir(self, job_id: str) -> Path:
        if not is_valid_job_id(job_id):
            raise WorkspacePermissionError("Invalid job ID.")
        path = self.contain(self.jobs_root / job_id)
        if path.parent != self.jobs_root:
            raise WorkspacePermissionError("Invalid job ID.")
        return path

    def create_job_dir(self, job_id: str) -> Path:
        path = self.job_dir(job_id)
        path.mkdir(parents=True, exist_ok=False)
        return path
