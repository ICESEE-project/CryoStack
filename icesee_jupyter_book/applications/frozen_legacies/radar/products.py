def upload_extension(kind: str, filename: str) -> tuple[str, str]:
    """Validate an uploaded filename for ``kind``; return (display name, extension)."""
    if kind not in UPLOAD_KINDS:
        raise ProductValidationError("Unsupported product type.")
    name = _FILENAME_CONTROL.sub("", unquote(str(filename or ""))).replace("\\", "/")
    name = name.rsplit("/", 1)[-1].strip()
    if not name or name in {".", ".."} or name.startswith(".") or len(name) > 200:
        raise ProductValidationError("The uploaded file needs a valid filename.")
    display = name
    extension = Path(name).suffix.lower()
    if extension not in KINDS[kind]["upload"]:
        allowed = ", ".join(KINDS[kind]["upload"])
        raise ProductValidationError(f"{KINDS[kind]['title']} files must be {allowed}.")
    return display, extension


def validate_upload(kind: str, path: Path, extension: str) -> dict:
    """Validate a stored upload; returns ``{"summary", "mime"}``."""
    if kind in CSV_KINDS:
        return {"summary": summarize_csv(kind, path), "mime": "text/csv"}
    if kind in JSON_KINDS:
        return {"summary": summarize_json(kind, path), "mime": "application/json"}
    info = validate_image(path, extension=extension)
    if kind == "astra-qc" and info["format"] != "PNG":
        raise ProductValidationError("ASTRA QC images are PNG files.")
    return {"summary": {"width": info["width"], "height": info["height"],
                        "format": info["format"], "mode": info["mode"]},
            "mime": info["mime"]}


def upload_record(kind: str, *, product_id: str, stored_name: str, display_name: str,
                  sha256: str, validated: dict) -> dict:
    return {
        "product_id": product_id,
        "kind": kind,
        "title": UPLOAD_TITLES.get(kind, KINDS[kind]["title"]),
        "file": stored_name,
        "download_name": display_name,
        "producer": "user",
        "workflow": "upload",
        "mime": validated["mime"],
        "created_at": time.time(),
        "provenance": {"origin": "user-provided", "original_filename": display_name,
                       "sha256": sha256},
        "summary": validated["summary"],
    }
