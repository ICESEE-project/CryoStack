# ── validation ───────────────────────────────────────────────────────
def _number(text: str) -> float | None:
    text = (text or "").strip()
    if text == "" or text.lower() in {"nan", "none"}:
        return None
    value = float(text)
    if not math.isfinite(value):
        return None
    return value


def _read_csv(path: Path) -> tuple[list[str], list[list[str]]]:
    size = path.stat().st_size
    if size > MAX_CSV_BYTES:
        raise ProductValidationError(
            f"CSV is {size // 1024} KB; the limit is {MAX_CSV_BYTES // 1024} KB.")
    try:
        text = path.read_bytes().decode("utf-8-sig")
    except UnicodeDecodeError:
        raise ProductValidationError("CSV files must be UTF-8 text.")
    if "\x00" in text:
        raise ProductValidationError("CSV files must be text.")
    try:
        rows = list(csv.reader(io.StringIO(text, newline="")))
    except csv.Error as error:
        raise ProductValidationError(f"The CSV could not be parsed: {error}")
    if not rows:
        raise ProductValidationError("The CSV is empty.")
    header = [h.strip() for h in rows[0]]
    body = [r for r in rows[1:] if any(c.strip() for c in r)]
    if len(body) > MAX_CSV_ROWS:
        raise ProductValidationError(f"The CSV has more than {MAX_CSV_ROWS:,} rows.")
    for line, row in enumerate(body, start=2):
        if len(row) != len(header):
            raise ProductValidationError(
                f"CSV line {line} has {len(row)} fields; the header has {len(header)}.")
    return header, body


def _check_numeric(header, body, columns, what):
    for column in columns:
        if column not in header:
            continue
        i = header.index(column)
        for line, row in enumerate(body, start=2):
            try:
                _number(row[i])
            except ValueError:
                raise ProductValidationError(
                    f"{what} line {line}: {column} is not a number.")


def _summary(header, body, *, cbd, lat, lon, thickness, count_label) -> dict:
    def values(column):
        if column not in header:
            return []
        i = header.index(column)
        out = []
        for row in body:
            try:
                v = _number(row[i])
            except ValueError:
                v = None
            if v is not None:
                out.append(v)
        return out

    cbds = values(cbd)
    lats, lons = values(lat), values(lon)
    thick = values(thickness)
    return {
        "rows": len(body),
        "row_label": count_label,
        "columns": len(header),
        "cbd_min": int(min(cbds)) if cbds else None,
        "cbd_max": int(max(cbds)) if cbds else None,
        "positions": min(len(lats), len(lons)),
        "thickness_values": len(thick),
        "thickness_min_m": round(min(thick), 2) if thick else None,
        "thickness_max_m": round(max(thick), 2) if thick else None,
    }


#: a frame whose transmitter pulse sits this far from the strip's median
#: (pixels, or dB for its power) is flagged for inspection
URSA_QC_TX_X_PX = 100
URSA_QC_TX_POWER_DB = 10.0


def ursa_frame_qc(header: list[str], body: list[list[str]]) -> list[dict]:
    """Frames whose transmitter detection departs from the rest of the strip.

    A display-only consistency check: on one film strip the transmitter
    pulse appears at nearly the same place and power in every frame, so a
    frame far from the median usually means another echo was taken for the
    transmitter (and surface/bed shift with it). Nothing in the CSV is
    changed; with fewer than three frames there is no median to compare to.
    """
    def column(name):
        if name not in header:
            return None
        i = header.index(name)
        out = []
        for row in body:
            try:
                out.append(_number(row[i]))
            except ValueError:
                out.append(None)
        return out

    frames, cbds = column("Frame"), column("CBD")
    checks = [(column("Transmitter_X_pixel"), URSA_QC_TX_X_PX, "transmitter position",
               lambda v, m: f"{v:.0f} px vs strip median {m:.0f} px"),
              (column("Transmitter_Power_dB"), URSA_QC_TX_POWER_DB, "transmitter power",
               lambda v, m: f"{v:.1f} dB vs strip median {m:.1f} dB")]
    flags: dict[int, dict] = {}
    for values, limit, label, describe in checks:
        present = sorted(v for v in (values or []) if v is not None)
        if len(present) < 3:
            continue
        mid = len(present) // 2
        median = present[mid] if len(present) % 2 else (present[mid - 1] + present[mid]) / 2
        for i, v in enumerate(values):
            if v is not None and abs(v - median) > limit:
                entry = flags.setdefault(i, {
                    "frame": int(frames[i]) if frames and frames[i] is not None else i + 1,
                    "cbd": int(cbds[i]) if cbds and cbds[i] is not None else None,
                    "checks": []})
                entry["checks"].append(f"{label}: {describe(v, median)}")
    return [flags[i] for i in sorted(flags)]


