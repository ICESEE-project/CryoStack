MAX_FRAME_ROWS = 500


def ursa_frame_table(path: Path) -> dict:
    """URSA's per-frame values exactly as written in its CSV (text, not
    reparsed or rounded) and the frame QC flags; ``{}`` when unreadable."""
    try:
        header, body = _read_csv(path)
    except (OSError, ProductValidationError):
        return {}
    if any(c not in header for c in URSA_REQUIRED):
        return {}
    columns = [c for c in URSA_FRAME_COLUMNS if c in header]
    index = [header.index(c) for c in columns]
    rows = [[row[i].strip()[:40] for i in index] for row in body[:MAX_FRAME_ROWS]]
    return {"columns": columns, "rows": rows, "truncated": len(body) > MAX_FRAME_ROWS,
            "qc_flags": ursa_frame_qc(header, body)}


def summarize_csv(kind: str, path: Path) -> dict:
    """Validate a picker/product CSV of ``kind`` and summarize it."""
    header, body = _read_csv(path)
    if kind == "astra-csv":
        if header != ASTRA_COLUMNS:
            raise ProductValidationError(
                "This is not an ASTRA CSV: the columns must be exactly ASTRA's output columns.")
        _check_numeric(header, body, [c for c in ASTRA_COLUMNS if c not in ("FLT", "Filename")],
                       "ASTRA CSV")
        return _summary(header, body, cbd="CBD", lat="LAT", lon="LON", thickness="h_ice_m",
                        count_label="A-scopes")
    if kind == "ursa-csv":
        missing = [c for c in URSA_REQUIRED if c not in header]
        if missing:
            raise ProductValidationError(
                "This is not a URSA picks CSV; missing column(s): " + ", ".join(missing))
        _check_numeric(header, body, URSA_REQUIRED, "URSA CSV")
        summary = _summary(header, body, cbd="CBD", lat="LAT", lon="LON",
                           thickness="Ice_Thickness_m", count_label="frames")
        summary["qc_flags"] = ursa_frame_qc(header, body)
        return summary
    if kind == "lyra-echoes-csv":
        missing = [c for c in LYRA_REQUIRED if c not in header]
        if missing:
            raise ProductValidationError(
                "This is not a LYRA echoes CSV; missing column(s): " + ", ".join(missing))
        _check_numeric(header, body, ["frame_idx", "cbd", "lat", "lon", "h_ice_m"], "LYRA CSV")
        return _summary(header, body, cbd="cbd", lat="lat", lon="lon", thickness="h_ice_m",
                        count_label="echoes")
    if kind == "navigation":
        rows = read_nav_csv(path)
        cbds = [r["cbd"] for r in rows]
        return {"rows": len(rows), "row_label": "navigation records",
                "cbd_min": min(cbds), "cbd_max": max(cbds),
                "positions": sum(1 for r in rows if r["lat"] is not None and r["lon"] is not None)}
    raise ProductValidationError(f"{kind} is not a CSV product.")


def summarize_json(kind: str, path: Path) -> dict:
    """Validate an uploaded LYRA calibration-guidance file (LYRA's own format,
    checked by the runner's validators) and summarize it."""
    from ..pickers.lyra_runner import GuidanceError, load_json, validate_derived, validate_picks

    if path.stat().st_size > MAX_JSON_BYTES:
        raise ProductValidationError(
            f"JSON files are limited to {MAX_JSON_BYTES // 1024} KB.")
    try:
        doc = load_json(str(path), validate_picks if kind == "lyra-guidance" else validate_derived)
    except UnicodeDecodeError:
        raise ProductValidationError("JSON files must be UTF-8 text.")
    except GuidanceError as error:
        raise ProductValidationError(str(error))
    if kind == "lyra-guidance":
        return {"rows": len(doc), "row_label": "frames with guidance",
                "frames_with_reference": sum(1 for v in doc.values() if v.get("ref") is not None),
                "frames_with_main_bang": sum(1 for v in doc.values() if v.get("mb") is not None),
                "frames_excluded": sum(1 for v in doc.values() if v.get("exclude"))}
    return {"x_spacing_px": doc.get("x_spacing_px"), "y_spacing_px": doc.get("y_spacing_px")}


def validate_image(path: Path, *, extension: str) -> dict:
    """Validate an uploaded image by its signature and decoded header."""
    expected = _EXT_FORMAT.get(extension)
    if expected is None:
        raise ProductValidationError("Unsupported image type.")
    size = path.stat().st_size
    if size > MAX_IMAGE_BYTES:
        raise ProductValidationError(
            f"Image is {size // (1024 * 1024)} MB; the limit is {MAX_IMAGE_BYTES // (1024 * 1024)} MB.")
    with path.open("rb") as handle:
        head = handle.read(16)
    if not any(head.startswith(sig) for sig in _SIGNATURES[expected]):
        raise ProductValidationError(
            f"The file is not a {expected} image (its contents do not match its extension).")
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", Image.DecompressionBombWarning)
        try:
            with Image.open(path) as image:
                fmt, (width, height), mode = image.format, image.size, image.mode
                frames = int(getattr(image, "n_frames", 1) or 1)
                if not (0 < width <= MAX_IMAGE_SIDE and 0 < height <= MAX_IMAGE_SIDE
                        and width * height <= MAX_IMAGE_PIXELS):
                    raise ProductValidationError(
                        f"Image dimensions {width} x {height} are outside the supported range.")
                image.verify()
        except ProductValidationError:
            raise
        except (Image.DecompressionBombError, OSError, ValueError, SyntaxError) as error:
            raise ProductValidationError(f"The image could not be read: {error}")
    if fmt != expected:
        raise ProductValidationError(f"The file is a {fmt} image, not {expected}.")
    if frames != 1:
        raise ProductValidationError("Multi-page images are not supported.")
    return {"format": fmt, "mime": _IMAGE_FORMATS[fmt], "width": width, "height": height,
            "mode": mode}


# ── products.json ────────────────────────────────────────────────────
def _empty_manifest(asset_id: str) -> dict:
    return {"schema": PRODUCTS_SCHEMA, "version": PRODUCTS_VERSION,
            "asset_id": asset_id, "products": []}


def _valid_record(record) -> bool:
    return (
        isinstance(record, dict)
        and is_valid_product_id(record.get("product_id"))
        and record.get("kind") in KINDS
        and isinstance(record.get("file"), str)
        and _valid_stored_name(record["file"])
        and record.get("producer") in {"frozen-legacies", "user"}
    )


def _valid_stored_name(name: str) -> bool:
    return re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,199}", name) is not None


def read_records(workspace: FrozenLegaciesWorkspace, asset_id: str) -> dict:
    path = workspace.asset_file(asset_id, ASSET_PRODUCTS)
    if not path.exists() or path.is_symlink():
        return _empty_manifest(asset_id)
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return _empty_manifest(asset_id)
    if (not isinstance(doc, dict) or doc.get("schema") != PRODUCTS_SCHEMA
            or doc.get("asset_id") != asset_id or not isinstance(doc.get("products"), list)):
        return _empty_manifest(asset_id)
    doc["products"] = [r for r in doc["products"] if _valid_record(r)]
    return doc


def write_records(workspace: FrozenLegaciesWorkspace, asset_id: str, doc: dict) -> None:
    path = workspace.asset_file(asset_id, ASSET_PRODUCTS)
    if path.is_symlink():
        raise PermissionError("products.json may not be a link.")
    text = json.dumps(doc, indent=2, sort_keys=True, allow_nan=False)
    manual._atomic_write(path, lambda tmp: tmp.write_text(text, encoding="utf-8"))


def new_product_id(prefix: str) -> str:
    return f"{prefix}-{uuid.uuid4().hex[:12]}"


def stored_file(workspace, asset_id: str, name: str) -> Path:
    """A stored product file under outputs/ (regular file, not a link)."""
    path = manual.output_path(workspace, asset_id, name)
    if os.path.lexists(path) and (path.is_symlink() or not path.is_file()):
        raise PermissionError("Product files must be regular files.")
    return path


def register(workspace, asset_id: str, record: dict, *, replace_kinds=()) -> dict:
    """Add a record to products.json (dropping same-workflow kinds listed in
    ``replace_kinds``, e.g. the previous automatic run)."""
    doc = read_records(workspace, asset_id)
    kept = []
    for existing in doc["products"]:
        if existing["kind"] in replace_kinds and existing.get("workflow") == record.get("workflow"):
            old = stored_file(workspace, asset_id, existing["file"])
            if old.exists() and old.name != record["file"]:
                old.unlink()
            continue
        kept.append(existing)
    kept.append(record)
    doc["products"] = kept
    write_records(workspace, asset_id, doc)
    return record


def replace_kind(workspace, asset_id: str, kind: str, workflow: str, records: list[dict]) -> None:
    """Replace every ``kind`` record of ``workflow`` by ``records`` in one
    write, removing stored files the new records do not reuse."""
    keep = {r["file"] for r in records}
    doc = read_records(workspace, asset_id)
    kept = []
    for existing in doc["products"]:
        if existing["kind"] == kind and existing.get("workflow") == workflow:
            old = stored_file(workspace, asset_id, existing["file"])
            if old.exists() and old.name not in keep:
                old.unlink()
            continue
        kept.append(existing)
    doc["products"] = kept + list(records)
    write_records(workspace, asset_id, doc)


def unregister(workspace, asset_id: str, product_id: str) -> None:
    doc = read_records(workspace, asset_id)
    remaining = []
    for record in doc["products"]:
        if record["product_id"] == product_id:
            path = stored_file(workspace, asset_id, record["file"])
            if path.exists():
                path.unlink()
            continue
        remaining.append(record)
    doc["products"] = remaining
    write_records(workspace, asset_id, doc)


def remove_workflow(workspace, asset_id: str, workflow: str) -> None:
    doc = read_records(workspace, asset_id)
    for record in [r for r in doc["products"] if r.get("workflow") == workflow]:
        unregister(workspace, asset_id, record["product_id"])


