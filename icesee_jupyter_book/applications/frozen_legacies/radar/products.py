def _public(record: dict, asset_id: str, path: Path | None) -> dict:
    kind = KINDS[record["kind"]]
    exists = path is not None and path.is_file()
    out = {
        "product_id": record["product_id"],
        "asset_id": asset_id,
        "kind": record["kind"],
        "title": record.get("title") or kind["title"],
        "type": kind["type"],
        "producer": record["producer"],
        "workflow": record.get("workflow"),
        "filename": record.get("download_name") or (path.name if path else None),
        "mime": record.get("mime") or kind["mime"],
        "bytes": path.stat().st_size if exists else None,
        "created_at": record.get("created_at") if record.get("created_at") is not None
        else (path.stat().st_mtime if exists else None),
        "available": exists,
        "downloadable": exists and record.get("downloadable", True),
        "previewable": exists and record["kind"] in IMAGE_KINDS,
        "provenance": record.get("provenance") or {},
        "summary": record.get("summary") or {},
    }
    if record.get("workflow") in AUTOMATIC_WORKFLOWS or record["kind"].startswith("ursa-"):
        # automatic picks are never scientifically validated by Frozen Legacies
        out["scientific_status"] = "unvalidated"
    if record["kind"] in DIAGNOSTIC_KINDS:
        out["diagnostic"] = DIAGNOSTIC_KINDS[record["kind"]]
    base = f"/frozen-legacies/api/assets/{asset_id}/products/{record['product_id']}"
    out["download_url"] = base if out["downloadable"] else None
    out["preview_url"] = f"{base}/preview" if out["previewable"] else None
    return out


def _asset_entries(workspace, manifest: dict, sources: dict) -> list[tuple[dict, Path | None]]:
    """``raw-radar`` and ``navigation`` of the asset itself."""
    asset_id = manifest["asset_id"]
    origin = manifest["origin"]
    entries = []
    if origin == "upload":
        tiff = workspace.asset_file(asset_id, ASSET_SOURCE_TIFF)
        entries.append(({
            "product_id": "raw-radar", "kind": "raw-radar", "file": ASSET_SOURCE_TIFF,
            "producer": "user", "workflow": "upload",
            "download_name": manifest.get("filename"),
            "created_at": manifest.get("created_at"),
            "provenance": {"origin": "upload", "sha256": manifest.get("sha256")},
            "summary": {"width": (manifest.get("image") or {}).get("width"),
                        "height": (manifest.get("image") or {}).get("height")},
        }, tiff if tiff.is_file() and not tiff.is_symlink() else None))
        nav = workspace.asset_file(asset_id, ASSET_NAV_CSV)
        if nav.is_file() and not nav.is_symlink():
            entries.append(({
                "product_id": "navigation", "kind": "navigation", "file": ASSET_NAV_CSV,
                "producer": "user", "workflow": "upload", "download_name": "nav.csv",
                "created_at": manifest.get("created_at"),
                "provenance": {"origin": "upload"},
                "summary": {k: (manifest.get("nav") or {}).get(k)
                            for k in ("rows", "cbd_min", "cbd_max", "positions")},
            }, nav))
    elif origin == "shared":
        source = sources.get(manifest.get("shared_source") or "")
        # Shared installation radar is shown but not offered for download.
        entries.append(({
            "product_id": "raw-radar", "kind": "raw-radar", "file": ASSET_SOURCE_TIFF,
            "producer": "frozen-legacies", "workflow": "radar-source",
            "download_name": manifest.get("filename"), "downloadable": False,
            "created_at": manifest.get("created_at"),
            "provenance": {"origin": "shared", "shared_source": manifest.get("shared_source"),
                           "available": source is not None},
            "summary": {"width": (manifest.get("image") or {}).get("width"),
                        "height": (manifest.get("image") or {}).get("height")},
        }, source.tiff_path if source else None))
    return entries


def _astra_entries(workspace, manifest: dict) -> list[tuple[dict, Path | None]]:
    """ASTRA manual outputs (owned by radar.manual)."""
    filename = manifest.get("filename")
    if not filename or manifest["origin"] == "products":
        return []
    asset_id = manifest["asset_id"]
    status = None
    rows = None
    session_path = workspace.asset_file(asset_id, "session.json")
    if session_path.is_file() and not session_path.is_symlink():
        try:
            doc = json.loads(session_path.read_text(encoding="utf-8"))
            status = doc.get("status")
            rows = len((doc.get("state") or {}).get("data") or [])
            row_sources = (doc.get("state") or {}).get("row_sources") or []
        except (OSError, ValueError):
            row_sources = []
    else:
        row_sources = []
    suggested = sum(1 for r in row_sources if isinstance(r, dict) and "suggested" in r.values())
    entries = []
    for kind in ("astra-csv", "astra-qc"):
        try:
            path = manual.existing_output(workspace, asset_id, filename, kind)
        except PermissionError:
            path = None
        if path is None:
            continue
        record = {
            "product_id": kind, "kind": kind, "file": path.name,
            "producer": "frozen-legacies", "workflow": "astra-manual",
            "provenance": {
                "picker": "ASTRA (manual)", "session_status": status,
                "a_scopes": rows,
                "a_scopes_with_suggested_picks": suggested,
                "source_filename": filename,
            },
        }
        if kind == "astra-csv":
            try:
                record["summary"] = summarize_csv("astra-csv", path)
            except ProductValidationError:
                record["summary"] = {}
        entries.append((record, path))
    return entries


def list_products(workspace, manifest: dict, sources: dict) -> list[dict]:
    asset_id = manifest["asset_id"]
    entries = _asset_entries(workspace, manifest, sources) + _astra_entries(workspace, manifest)
    for record in read_records(workspace, asset_id)["products"]:
        try:
            path = stored_file(workspace, asset_id, record["file"])
        except PermissionError:
            path = None
        entries.append((record, path if path is not None and path.is_file() else None))
    return [_public(record, asset_id, path) for record, path in entries]


def resolve_product(workspace, manifest: dict, sources: dict, product_id: str):
    """``(public record, path)`` of a downloadable product owned by this user."""
    if not is_valid_product_id(product_id):
        raise AssetNotFoundError(product_id)
    asset_id = manifest["asset_id"]
    entries = _asset_entries(workspace, manifest, sources) + _astra_entries(workspace, manifest)
    for record in read_records(workspace, asset_id)["products"]:
        try:
            entries.append((record, stored_file(workspace, asset_id, record["file"])))
        except PermissionError:
            continue
    for record, path in entries:
        if record["product_id"] != product_id:
            continue
        public = _public(record, asset_id, path if path is not None and path.is_file() else None)
        if path is None or not public["available"]:
            raise AssetNotFoundError(product_id)
        if path.is_symlink():
            raise PermissionError("Product files must be regular files.")
        return public, path
    raise AssetNotFoundError(product_id)


