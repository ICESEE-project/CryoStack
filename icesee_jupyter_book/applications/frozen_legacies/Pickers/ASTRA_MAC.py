def get_processed_output_basenames(output_dir):
    if not output_dir or not os.path.isdir(output_dir):
        return set()

    processed_basenames = set()
    for csv_path in glob.glob(os.path.join(output_dir, '*.csv')):
        processed_basenames.add(os.path.splitext(os.path.basename(csv_path))[0])
    return processed_basenames

def get_next_unprocessed_tiff(tiff_candidates, output_dir, start_index=0):
    processed_basenames = get_processed_output_basenames(output_dir)

    for index in range(start_index, len(tiff_candidates)):
        candidate_path = tiff_candidates[index]
        candidate_basename = os.path.splitext(os.path.basename(candidate_path))[0]
        if candidate_basename not in processed_basenames:
            return index, candidate_path

    return None, None

