def _get_full_window_bbox():
    """Return (left, top, right, bottom) of the whole OS window, excluding the invisible resize border."""
    if sys.platform.startswith('win'):
        try:
            GA_ROOT = 2
            hwnd = ctypes.windll.user32.GetAncestor(ctypes.wintypes.HWND(root.winfo_id()), GA_ROOT)
            rect = ctypes.wintypes.RECT()
            DWMWA_EXTENDED_FRAME_BOUNDS = 9
            hr = ctypes.windll.dwmapi.DwmGetWindowAttribute(
                hwnd, DWMWA_EXTENDED_FRAME_BOUNDS, ctypes.byref(rect), ctypes.sizeof(rect)
            )
            if hr == 0:
                return (rect.left, rect.top, rect.right, rect.bottom)
            ctypes.windll.user32.GetWindowRect(hwnd, ctypes.byref(rect))
            return (rect.left, rect.top, rect.right, rect.bottom)
        except Exception:
            pass
    x = root.winfo_rootx()
    y = root.winfo_rooty()
    return (x, y, x + root.winfo_width(), y + root.winfo_height())

def _grab_astra_window():
    """Grab the ASTRA window while preserving the existing Windows behavior."""
    bbox = _get_full_window_bbox()
    screenshot = ImageGrab.grab(bbox=bbox)

    if sys.platform == 'darwin':
        # Pillow may return Retina backing pixels (commonly 2x logical size).
        # Normalize to Tk's logical window dimensions before the existing 3x
        # publication upscale so Mac exports match Windows output dimensions.
        expected_w = max(1, int(bbox[2] - bbox[0]))
        expected_h = max(1, int(bbox[3] - bbox[1]))
        if (screenshot.width, screenshot.height) != (expected_w, expected_h):
            ratio_w = screenshot.width / expected_w
            ratio_h = screenshot.height / expected_h
            if 1.5 <= ratio_w <= 3.0 and 1.5 <= ratio_h <= 3.0:
                screenshot = screenshot.resize((expected_w, expected_h), Image.LANCZOS)

    return screenshot

def export_publication_screenshot():
    """Capture the whole ASTRA window exactly as shown and save it as a 600 DPI TIFF."""
    save_path = filedialog.asksaveasfilename(
        title="Export ASTRA screenshot",
        defaultextension=".tiff",
        filetypes=[("TIFF image", "*.tiff *.tif")],
        initialfile=f"{current_filename}_ASTRA_screenshot.tiff"
    )
